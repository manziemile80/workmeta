"""Object storage abstraction.

Stage 2 ships a local-disk provider; the interface is intentionally async and
S3-shaped so a production backend can replace it without touching the API layer.
Keys are generated by the server (never the uploaded filename) and are always
resolved inside the configured root.
"""

from __future__ import annotations

import asyncio
import os
import uuid
from pathlib import Path
from typing import Protocol

from app.core.config import Settings, get_settings
from app.core.errors import AppError


class StorageProvider(Protocol):
    async def save(self, key: str, data: bytes) -> None: ...

    async def read(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...

    async def exists(self, key: str) -> bool: ...


def generate_storage_key(*, org_id: uuid.UUID, assistant_id: uuid.UUID) -> str:
    """Return an unpredictable, tenant-prefixed key with no original filename."""
    return f"{org_id}/{assistant_id}/{uuid.uuid4().hex}"


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        candidate = (self.root / key).resolve()
        if candidate != self.root and self.root not in candidate.parents:
            raise AppError(
                "The stored object key is invalid.",
                status_code=500,
                code="storage_key_invalid",
            )
        return candidate

    async def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        await asyncio.to_thread(self._write, path, data)

    @staticmethod
    def _write(path: Path, data: bytes) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix(path.suffix + ".part")
        temporary.write_bytes(data)
        os.replace(temporary, path)

    async def read(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return await asyncio.to_thread(path.read_bytes)
        except FileNotFoundError as exc:
            raise AppError(
                "The stored file is missing. Re-upload the document.",
                status_code=410,
                code="document_file_missing",
            ) from exc

    async def delete(self, key: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.unlink, missing_ok=True)

    async def exists(self, key: str) -> bool:
        path = self._path(key)
        return await asyncio.to_thread(path.is_file)


def build_storage(settings: Settings | None = None) -> StorageProvider:
    settings = settings or get_settings()
    if settings.storage_backend == "local":
        return LocalStorage(settings.resolved_storage_dir)
    raise AppError(
        "The configured storage backend is not available yet.",
        status_code=500,
        code="storage_backend_unavailable",
    )


def get_storage() -> StorageProvider:
    """FastAPI dependency. Tests override this to use a temporary directory."""
    return build_storage()
